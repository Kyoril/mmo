// Converts one HLSL shader into a Metal shader blob and writes it as a C++ header holding a byte
// array, the Metal counterpart of the headers fxc generates for the D3D11 build.
//
// Usage: hlsl2msl <input.hlsl> <vs|ps|cs> <output.h> <symbol> [entry point]

#include "msl_cross/msl_cross.h"

#include <filesystem>
#include <fstream>
#include <iostream>
#include <sstream>

namespace
{
	std::optional<std::string> ReadTextFile(const std::filesystem::path& path)
	{
		std::ifstream file(path, std::ios::binary);
		if (!file)
		{
			return std::nullopt;
		}

		std::ostringstream content;
		content << file.rdbuf();
		return content.str();
	}
}

int main(const int argc, char* argv[])
{
	if (argc < 5)
	{
		std::cerr << "Usage: hlsl2msl <input.hlsl> <vs|ps|cs> <output.h> <symbol> [entry point]" << std::endl;
		return 1;
	}

	const std::filesystem::path inputPath = argv[1];
	const std::string stageName = argv[2];
	const std::filesystem::path outputPath = argv[3];
	const std::string symbol = argv[4];

	mmo::msl_cross::CompileInput input;
	if (stageName == "vs")
	{
		input.stage = mmo::metal_shader_blob::Stage::Vertex;
	}
	else if (stageName == "ps")
	{
		input.stage = mmo::metal_shader_blob::Stage::Pixel;
	}
	else if (stageName == "cs")
	{
		input.stage = mmo::metal_shader_blob::Stage::Compute;
	}
	else
	{
		std::cerr << "Unknown shader stage '" << stageName << "', expected vs, ps or cs" << std::endl;
		return 1;
	}

	if (argc > 5)
	{
		input.entryPoint = argv[5];
	}

	const std::optional<std::string> source = ReadTextFile(inputPath);
	if (!source)
	{
		std::cerr << "Unable to read " << inputPath << std::endl;
		return 1;
	}

	input.source = *source;
	input.sourceName = inputPath.string();

	const std::filesystem::path includeDirectory = inputPath.parent_path();
	input.includeResolver = [&includeDirectory](const std::string& includeName, const std::string& includerName) -> std::optional<std::string>
	{
		const std::filesystem::path includer(includerName);
		if (includer.has_parent_path())
		{
			if (auto content = ReadTextFile(includer.parent_path() / includeName))
			{
				return content;
			}
		}

		return ReadTextFile(includeDirectory / includeName);
	};

	mmo::msl_cross::CompileOutput output;
	if (!mmo::msl_cross::CompileHlslToMsl(input, output))
	{
		std::cerr << inputPath.string() << ": cross compilation failed\n" << output.log << std::endl;
		return 1;
	}

	const std::vector<mmo::uint8> blob = output.ToBlob(input.stage);

	std::ostringstream header;
	header << "// Generated by hlsl2msl from " << inputPath.filename().string() << ". Do not edit.\n"
		<< "#pragma once\n\n"
		<< "static const unsigned char " << symbol << "[] = {";
	for (size_t i = 0; i < blob.size(); ++i)
	{
		if (i % 24 == 0)
		{
			header << "\n\t";
		}

		header << static_cast<unsigned>(blob[i]) << ",";
	}
	header << "\n};\n";

	std::filesystem::create_directories(outputPath.parent_path());
	std::ofstream outFile(outputPath, std::ios::binary | std::ios::trunc);
	if (!outFile)
	{
		std::cerr << "Unable to write " << outputPath << std::endl;
		return 1;
	}

	outFile << header.str();
	return 0;
}
