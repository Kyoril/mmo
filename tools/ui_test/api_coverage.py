"""Lists the Lua globals the game client registers in C++ and which of them the ui_test mocks cover.

The client binds its game API with luabind (luabind::def, luabind::def<...>, luabind::def_lambda and
luabind::globals(...)["name"]). The UI test app has none of that, so every function a layout calls
needs a Lua mock in tools/ui_test/mocks. This script finds the gaps.

    python tools/ui_test/api_coverage.py               # summary + missing functions with their source file
    python tools/ui_test/api_coverage.py --used        # only functions the UI's Lua/XML actually calls
    python tools/ui_test/api_coverage.py --grep Friend # filter by name
"""

import argparse
import pathlib
import re
import sys

REPO = pathlib.Path(__file__).resolve().parents[2]
CLIENT_SOURCES = [REPO / "src/mmo_client", REPO / "src/shared/game_client"]
MOCKS = REPO / "tools/ui_test/mocks"
STUBS = MOCKS / "01_api_stubs.lua"

DEF_PATTERN = re.compile(r'luabind::(?:def|def_lambda)\s*(?:<[^"]*?>)?\s*\(\s*"([A-Za-z_][A-Za-z_0-9]*)"')
GLOBAL_PATTERN = re.compile(r'luabind::globals\([^)]*\)\s*\[\s*"([A-Za-z_][A-Za-z_0-9]*)"\s*\]\s*=')
MOCK_PATTERN = re.compile(r'^\s*(?:function\s+([A-Za-z_][A-Za-z_0-9]*)\s*\(|([A-Za-z_][A-Za-z_0-9]*)\s*=)', re.M)


def find_ui_root():
    """The nearest data/client/Interface upwards from the repository (worktrees have empty data submodules)."""
    for folder in [REPO, *REPO.parents]:
        candidate = folder / "data/client/Interface"
        if (candidate / "GameUI/GameUI.toc").exists():
            return candidate
    return None


def client_api():
    api = {}
    for root in CLIENT_SOURCES:
        for path in root.rglob("*.cpp"):
            text = path.read_text(encoding="utf-8", errors="ignore")
            for pattern in (DEF_PATTERN, GLOBAL_PATTERN):
                for match in pattern.finditer(text):
                    line = text.count("\n", 0, match.start()) + 1
                    api.setdefault(match.group(1), f"{path.relative_to(REPO).as_posix()}:{line}")
    return api


def write_stubs(api):
    """Every client API function as a stub that returns nothing and reports the call as unmocked."""
    lines = [
        "-- GENERATED by tools/ui_test/api_coverage.py --write-stubs. Do not edit; mock in a later file instead.",
        "-- Every Lua global the game client registers in C++, as a stub that returns nil and is listed",
        "-- under \"unmockedCalls\" in status.json when the UI calls it. Mocks loaded after this file replace them.",
        "UiTest.StubApi({",
    ]
    lines += [f'\t"{name}",' for name in sorted(api)]
    lines.append("})")
    STUBS.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"Wrote {len(api)} stubs to {STUBS.relative_to(REPO).as_posix()}")


def mocked_names():
    names = set()
    for path in MOCKS.glob("*.lua"):
        if path == STUBS:
            continue
        for match in MOCK_PATTERN.finditer(path.read_text(encoding="utf-8", errors="ignore")):
            names.add(match.group(1) or match.group(2))
    return names


def used_names(ui_root):
    text = []
    for path in ui_root.rglob("*"):
        if path.suffix.lower() in (".lua", ".xml"):
            text.append(path.read_text(encoding="utf-8", errors="ignore"))
    return set(re.findall(r"\b([A-Za-z_][A-Za-z_0-9]*)\b", "\n".join(text)))


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--used", action="store_true", help="only list functions the UI files reference")
    parser.add_argument("--grep", default="", help="only list names containing this text (case-insensitive)")
    parser.add_argument("--all", action="store_true", help="list mocked functions too")
    parser.add_argument("--write-stubs", action="store_true", help=f"regenerate {STUBS.relative_to(REPO).as_posix()}")
    args = parser.parse_args()

    api = client_api()
    if args.write_stubs:
        write_stubs(api)
        return 0

    mocked = mocked_names()
    used = None
    if args.used:
        ui_root = find_ui_root()
        if not ui_root:
            print("data/client/Interface not found", file=sys.stderr)
            return 2
        used = used_names(ui_root)

    names = sorted(n for n in api if (used is None or n in used) and args.grep.lower() in n.lower())
    covered = [n for n in names if n in mocked]
    missing = [n for n in names if n not in mocked]

    print(f"{len(covered)}/{len(names)} client Lua globals mocked" + (" (referenced by the UI)" if used is not None else ""))
    for name in (names if args.all else missing):
        mark = "  mocked " if name in mocked else "  MISSING"
        print(f"{mark} {name:40} {api[name]}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
